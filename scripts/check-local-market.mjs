import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { erc20Abi, parseEther } from 'viem';
import { LocalChain } from '../src/chain.mjs';
import { LocalMarkets } from '../src/market.mjs';

const chain = new LocalChain(process.env.ANVIL_ORIGIN);
let clock = Date.now();
let markets = new LocalMarkets(chain, { now: () => clock });
let project = { id: randomUUID(), name: 'Market integration fixture', symbol: 'MKTTEST', chain: null };
const file = join(mkdtempSync(join(tmpdir(), 'veyl-market-')), 'project.json');
const save = () => writeFileSync(file, JSON.stringify(project));
project.chain = await markets.launch(project, save); save();
const market = project.chain;
assert.equal(market.buyFeeBps, 300);
assert.equal(market.lpFeePips, 0);
assert.equal((BigInt(market.hook) & 0x3fffn), 0x20ccn);
assert.equal((await markets.launch(project, save)).token, market.token);
assert.equal(await chain.client.readContract({ address: market.token, abi: erc20Abi, functionName: 'totalSupply' }), parseEther('1000000000'));
const treasuryBefore = await chain.client.getBalance({ address: market.treasury });
const platformBefore = await chain.client.getBalance({ address: market.platform });
const quote = await markets.quote(project, { side: 'buy', amount: '0.01', slippageBps: 50 }, save);
assert.equal(quote.feeEth, '0.0003');
const buy = await markets.swap(project, { quoteId: quote.id }, save);
assert.equal(buy.actualOutput, quote.expectedOutput);
const count = await chain.client.getTransactionCount({ address: chain.account });
project = JSON.parse(readFileSync(file, 'utf8'));
markets = new LocalMarkets(new LocalChain(), { now: () => clock });
const recovered = await markets.swap(project, { quoteId: quote.id }, save);
assert.equal(recovered.hash, buy.hash);
assert.equal(await chain.client.getTransactionCount({ address: chain.account }), count, 'Replay after restart must not transact');
const sellQuote = await markets.quote(project, { side: 'sell', amount: '100000', slippageBps: 50 }, save);
const sell = await markets.swap(project, { quoteId: sellQuote.id }, save);
assert.equal(sell.actualOutput, sellQuote.expectedOutput);
const expired = await markets.quote(project, { side: 'buy', amount: '0.001' }, save);
clock += 121000;
await assert.rejects(markets.swap(project, { quoteId: expired.id }, save), /expired/);
const pending = parseEther((await markets.status(project)).pendingFees);
assert.ok(pending > parseEther('0.0003'));
await markets.harvest(project);
assert.equal(await chain.client.getBalance({ address: market.treasury }) - treasuryBefore, pending * 7000n / 10000n);
assert.equal(await chain.client.getBalance({ address: market.platform }) - platformBefore, pending - pending * 7000n / 10000n - pending * 2000n / 10000n);
assert.equal((await markets.status(project)).pendingFees, '0');
assert.deepEqual((await chain.revenueStatus(project)).claimable, { treasury: '0', creator: '0', platform: '0' });
assert.equal((await markets.harvest(project)).amount, '0');
console.log(JSON.stringify({ result: 'passed', chainId: 31337, checks: ['atomic full-range launch', '1B supply', 'CREATE2 permission bits', 'idempotent launch', 'actual buy/sell quotes', 'buy/sell execution', 'restart replay protection', 'expired quote refusal', '70/20/10 real swap fees', 'repeat harvest no-op'], poolId: market.poolId, fixture: file }, null, 2));
